def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default=DEFAULT_INPUT_FILE)
    parser.add_argument("--output", default=DEFAULT_OUTPUT_FILE)
    parser.add_argument("--cache_dir", default=DEFAULT_CACHE_DIR, help="Path to your external hard drive folder")
    args = parser.parse_args()

    # The model will download to args.cache_dir if it's not already there
    print(f"📦 Initializing {MODEL_ID}...")
    tokenizer, model = load_prometheus(MODEL_ID, cache_dir=args.cache_dir)

    input_path = Path(args.input)
    output_path = Path(args.output)

    with open(input_path, "r", encoding="utf-8") as f:
        cases = [json.loads(line) for line in f]

    print(f"🚀 Evaluating {len(cases)} cases...")
    
    # Initialize statistics
    stats = {
        "count": 0,
        "score_sum": 0.0,
        "consistent_count": 0
    }

    with open(output_path, "a", encoding="utf-8") as f_out:
        pbar = tqdm(cases, desc="Evaluating (Pairwise)")
        for case in pbar:
            gt = case.get("caption") or ""
            base_r = case.get("model_base_response") or ""
            ft_r = case.get("model_ft_response") or ""

            eval_res = evaluate_pairwise(tokenizer, model, gt, base_r, ft_r)

            # Update statistics
            stats["count"] += 1
            if eval_res["score"] is not None:
                stats["score_sum"] += eval_res["score"]
            if eval_res.get("consistent"):
                stats["consistent_count"] += 1

            # Update progress bar
            avg_score = stats["score_sum"] / stats["count"]
            consistency = (stats["consistent_count"] / stats["count"]) * 100
            
            pbar.set_postfix({
                "avg_score": f"{avg_score:.3f}",
                "consistency": f"{consistency:.1f}%"
            })

            res = {
                "case_id": case.get("file_name"),
                "pairwise": eval_res
            }

            json.dump(res, f_out, ensure_ascii=False)
            f_out.write("\n")
            f_out.flush()

if __name__ == "__main__":
    main()