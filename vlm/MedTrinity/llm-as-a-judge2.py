# 3. PROMETHEUS INFERENCE HELPER
# ─────────────────────────────────────────────

def load_prometheus(model_id, cache_dir=None):
    """
    Loads tokenizer and model. If cache_dir is provided, it downloads/loads 
    the model from that specific location.
    """
    if cache_dir:
        print(f"📂 Storage directory set to: {cache_dir}")
    
    # Load tokenizer and model using the specified cache directory
    tokenizer = AutoTokenizer.from_pretrained(
        model_id, 
        cache_dir=cache_dir
    )
    
    model = AutoModelForCausalLM.from_pretrained(
        model_id, 
        device_map="auto", 
        torch_dtype=torch.bfloat16,
        trust_remote_code=True,
        cache_dir=cache_dir
    )
    return tokenizer, model



def call_prometheus(tokenizer, model, prompt, max_new_tokens=100):
    """
    Handles local inference using Prometheus chat template.
    """
    messages = [
        {"role": "user", "content": prompt},
    ]
    
    inputs = tokenizer.apply_chat_template(
        messages,
        add_generation_prompt=True,
        tokenize=True,
        return_dict=True,
        return_tensors="pt",
    ).to(model.device)

    with torch.no_grad():
        outputs = model.generate(**inputs, max_new_tokens=max_new_tokens)
    
    decoded = tokenizer.decode(outputs[0][inputs["input_ids"].shape[-1]:], skip_special_tokens=True)
    return decoded.strip()

def extract_score(text):
    """
    Regex to find the last numerical value in the output.
    """
    if not text: return None
    match = re.findall(r"[-+]?\d*\.?\d+", text)
    if match:
        try:
            val = float(match[-1])
            return max(-1.0, min(1.0, val))
        except: return None
    return None

# ─────────────────────────────────────────────
# 3. EVALUATION FUNCTIONS
# ─────────────────────────────────────────────

def evaluate_pairwise(tokenizer, model, gt, base, ft):
    """
    Performs pairwise evaluation with Prometheus.
    """
    prompt_ab = f"{RUBRIC_PAIRWISE}\n\nREF:\n{gt}\n\nREPORT A:\n{base}\n\nREPORT B:\n{ft}"
    raw_s1 = call_prometheus(tokenizer, model, prompt_ab)
    s1 = extract_score(raw_s1)
    
    prompt_ba = f"{RUBRIC_PAIRWISE}\n\nREF:\n{gt}\n\nREPORT A:\n{ft}\n\nREPORT B:\n{base}"
    raw_s2 = call_prometheus(tokenizer, model, prompt_ba)
    s2 = extract_score(raw_s2)

    if s1 is None or s2 is None:
        return {"score": None, "consistent": False, "raw": [raw_s1, raw_s2]}

    final_score = (s1 - s2) / 2.0
    consistent = (s1 * s2 < 0) or (s1 == 0 and s2 == 0)

    return {
        "score": round(final_score, 4),
        "consistent": consistent
    }

